    public const int GlyphWidth = 5;
    public const int Advance = 6;
    public const int LineHeight = 12;

    public static int Measure(string text, int scale) => text.Length * Advance * scale;

    public static void Draw(Batch batch, string text, double x, double y, int scale, uint color)
    {
        for (int c = 0; c < text.Length; c++)
        {
            if (!Glyphs.TryGetValue(text[c], out var rows))
                rows = Glyphs['?'];
            double gx = x + c * Advance * scale;
            for (int row = 0; row < rows.Length; row++)
            {
                int bits = rows[row];
                int column = 0;
                while (column < GlyphWidth)
                {
                    if ((bits & (1 << (GlyphWidth - 1 - column))) == 0)
                    {
                        column++;
                        continue;
                    }
                    int start = column;
                    while (column < GlyphWidth && (bits & (1 << (GlyphWidth - 1 - column))) != 0)
                        column++;
                    batch.Rect(gx + start * scale, y + row * scale, (column - start) * scale, scale, color);
                }
            }
        }
    }

    public static void DrawShadowed(Batch batch, string text, double x, double y, int scale, uint color)
    {
        Draw(batch, text, x + scale * 0.5, y + scale * 0.5, scale, Rgba.Hex(0x000000, 0.7));
        Draw(batch, text, x, y, scale, color);
    }

    static Dictionary<char, byte[]> Build()
    {
        var glyphs = new Dictionary<char, byte[]>();
        foreach (var (c, pattern) in Source)
        {
            var rows = pattern.Split(' ');
            var bits = new byte[rows.Length];
            for (int r = 0; r < rows.Length; r++)
                for (int i = 0; i < GlyphWidth; i++)
                    if (rows[r][i] == '#')
                        bits[r] |= (byte)(1 << (GlyphWidth - 1 - i));
            glyphs[c] = bits;
        }
        return glyphs;
    }

